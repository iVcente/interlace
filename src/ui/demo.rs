//! The scripted demo-video recorder: drives the real `InterlaceApp` through a
//! tour of its features and encodes the frames into an MP4.
//!
//! Nothing here is screen-captured. The app runs headless inside an
//! `egui_kittest` harness, which steps it one frame at a time with a fixed
//! `dt`, so animations are smooth no matter how slow a frame is to render. The
//! script acts through real input events (pointer moves, clicks, drags, typed
//! text, hovered and dropped files), so every hover state, drag line and
//! overlay on screen is the app's own reaction. Widgets are found by their
//! AccessKit labels rather than hard-coded coordinates, and the table rows,
//! which are painted rather than labelled, by their known geometry.
//!
//! Each video frame is composed from two egui contexts: the app at its window
//! size, rendered with kittest's wgpu renderer, and a "stage" (gradient
//! backdrop, the app's drop shadow, captions and title cards) at the video's
//! full size. The app image is pasted onto the stage with rounded corners and
//! the result streams as raw RGBA into an `ffmpeg` that encodes H.264.
//!
//! The sample media (a synthetic episode, a dub and a fan subtitle) is
//! generated by ffmpeg into `demo/media` on the first run; it's gitignored.
//! The recording needs ffmpeg/ffprobe, so it's an ignored test:
//! `cargo test --release record_demo -- --ignored --nocapture`, with
//! `DEMO_OUT` set to the MP4 to write. Without it, only the stills the script
//! asks for are saved (to `DEMO_STILLS`, default `target/demo`), which is the
//! quick way to check a script change.

use super::{InterlaceApp, theme};
use egui::{Color32, Pos2, Rect, Shape, Stroke, Vec2, pos2, vec2};
use egui_kittest::kittest::{NodeT, Queryable};
use egui_kittest::wgpu::WgpuTestRenderer;
use egui_kittest::{Harness, TestRenderer};
use std::cell::RefCell;
use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::{Child, ChildStdin, Command, Stdio};
use std::rc::Rc;

/// Video frame size in pixels.
const VIDEO: [u32; 2] = [1920, 1080];
/// Video frame rate; also the harness's step, so app time matches video time.
const FPS: u32 = 60;
/// The app window's size in points. Wide enough for the wide layout.
const WINDOW: Vec2 = vec2(1440.0, 810.0);
/// Window scale: 1440 points become 1600 pixels, so text stays readable in a
/// 1080p video while the app keeps its desktop proportions.
const PPP: f32 = 1600.0 / 1440.0;
/// Where the app image sits on the stage, in pixels.
const APP_ORIGIN: [u32; 2] = [160, 26];
/// The app image's rounded-corner radius, in pixels.
const APP_RADIUS: f32 = 14.0;

/// A wgpu renderer both the harness and the recorder hold. The harness feeds it
/// every frame's texture changes (the font atlas, icons); the recorder renders
/// with it, adding its own cursor, which kittest would otherwise draw as a
/// plain triangle.
struct SharedRenderer(Rc<RefCell<WgpuTestRenderer>>);

impl TestRenderer for SharedRenderer {
    /// @see more info in egui_kittest's `TestRenderer`.
    fn handle_delta(&mut self, delta: &egui::TexturesDelta) {
        self.0.borrow_mut().handle_delta(delta);
    }

    /// @see more info in egui_kittest's `TestRenderer`.
    fn render(&mut self, ctx: &egui::Context, output: &egui::FullOutput) -> Result<image::RgbaImage, String> {
        self.0.borrow_mut().render(ctx, output)
    }
}

/// The harness state: the app, plus whether the theme is installed yet.
struct Shell {
    /// The app under the script.
    app: InterlaceApp,
    /// False for the harness's first frame, which only installs the theme: the
    /// app's `medium` font family doesn't exist until then.
    ready: bool,
    /// A file chip to paint by the cursor (position in points, label) during a
    /// file drag. Painted inside the app's frame, so its glyphs reach the font
    /// atlas before the frame is rendered.
    chip: Option<(Pos2, String)>,
}

/// A caption under the app window: a step tag, a headline and a line of detail.
#[derive(Clone)]
struct Caption {
    /// Small accent label above the headline, like "01 · OPEN".
    tag: String,
    /// The headline.
    title: String,
    /// One line of explanation under it.
    detail: String,
}

/// A full-screen card between scenes (the intro, an idea, the outro).
#[derive(Clone)]
struct Card {
    /// Small accent label above the headline.
    tag: String,
    /// The big headline.
    title: String,
    /// Lines under it.
    lines: Vec<String>,
    /// Whether to show the app icon above the headline (intro and outro).
    logo: bool,
    /// Whether to animate a stream list under the text (the idea card).
    art: bool,
}

/// Drives the app and writes the video.
struct Recorder<'a> {
    /// The headless app.
    harness: Harness<'a, Shell>,
    /// The renderer the harness also feeds, for the app image.
    app_renderer: Rc<RefCell<WgpuTestRenderer>>,
    /// The stage: backdrop, captions and cards, at video size.
    stage: egui::Context,
    /// Renders the stage.
    stage_renderer: WgpuTestRenderer,
    /// The app icon, as a stage texture.
    logo: egui::TextureHandle,
    /// The encoder reading raw frames on stdin; `None` for stills-only runs.
    encoder: Option<(Child, ChildStdin)>,
    /// Frames written so far.
    frame: u64,
    /// The cursor's position in app points, or `None` while it's off-window.
    cursor: Option<Pos2>,
    /// Whether the primary button is held.
    pressed: bool,
    /// Video time of the last click, for the ripple.
    last_click: Option<(f64, Pos2)>,
    /// The caption shown now, and the one fading out with when it was replaced.
    caption: Option<Caption>,
    old_caption: Option<Caption>,
    /// Video time the current caption changed.
    caption_since: f64,
    /// The card shown, if any, and how opaque its backdrop is (0 shows the app).
    card: Option<Card>,
    card_alpha: f32,
    /// The card whose text is fading out as `card`'s fades in.
    old_card: Option<Card>,
    /// Video time `card` appeared; its text fades in and its art animates from here.
    card_since: f64,
    /// Files hovering over the window this frame (a drag from Explorer).
    hovering: Vec<PathBuf>,
    /// Files to drop on the next frame.
    dropping: Vec<PathBuf>,
    /// The label of the file chip carried by the cursor during a file drag.
    chip: Option<String>,
    /// Modifiers held for the next pointer and key events.
    modifiers: egui::Modifiers,
    /// Write only every n-th frame (1 = all), to speed through a long run.
    fast_forward: u64,
    /// Frames stepped, written or not; `fast_forward` counts these.
    stepped: u64,
    /// Where to save stills on request.
    stills: PathBuf,
}

impl<'a> Recorder<'a> {
    /// A recorder with the app open on an empty session, encoding to `out` (or
    /// not encoding at all when `out` is `None`).
    fn new(out: Option<&Path>, stills: PathBuf) -> Self {
        let app_renderer = Rc::new(RefCell::new(WgpuTestRenderer::from_setup(gpu_setup())));
        let mut app = InterlaceApp::empty();
        app.recheck_binaries();
        let harness = Harness::builder()
            .with_size(WINDOW)
            .with_pixels_per_point(PPP)
            .with_step_dt(1.0 / FPS as f32)
            .with_max_steps(1)
            .renderer(SharedRenderer(app_renderer.clone()))
            .build_ui_state(
                |ui, shell: &mut Shell| {
                    if shell.ready {
                        shell.app.render(ui);
                        if let Some((pos, label)) = &shell.chip {
                            file_chip(ui.ctx(), *pos, label);
                        }
                    } else {
                        theme::install(ui.ctx(), true);
                        shell.ready = true;
                    }
                },
                Shell { app, ready: false, chip: None },
            );
        // The harness turns animations off for stable snapshots; a video wants them.
        harness.ctx.all_styles_mut(|s| s.animation_time = 1.0 / 12.0);

        let stage = egui::Context::default();
        theme::install(&stage, false);
        let icon = image::load_from_memory(include_bytes!("../../assets/icon.png")).expect("icon.png").to_rgba8();
        let icon = egui::ColorImage::from_rgba_unmultiplied([icon.width() as _, icon.height() as _], icon.as_raw());
        let logo = stage.load_texture("logo", icon, egui::TextureOptions::LINEAR);

        let encoder = out.map(|out| {
            let mut child = Command::new("ffmpeg")
                .args(["-hide_banner", "-loglevel", "error", "-y", "-f", "rawvideo", "-pix_fmt", "rgba"])
                .args(["-s", &format!("{}x{}", VIDEO[0], VIDEO[1]), "-r", &FPS.to_string(), "-i", "-"])
                .args(["-c:v", "libx264", "-preset", "slow", "-crf", "16", "-tune", "animation"])
                .args(["-pix_fmt", "yuv420p", "-movflags", "+faststart"])
                .arg(out)
                .stdin(Stdio::piped())
                .spawn()
                .expect("ffmpeg must be on PATH to record");
            let stdin = child.stdin.take().unwrap();
            (child, stdin)
        });

        let mut rec = Self {
            harness,
            app_renderer,
            stage,
            stage_renderer: WgpuTestRenderer::from_setup(gpu_setup()),
            logo,
            encoder,
            frame: 0,
            cursor: None,
            pressed: false,
            last_click: None,
            caption: None,
            old_caption: None,
            caption_since: 0.0,
            card: None,
            card_alpha: 0.0,
            old_card: None,
            card_since: 0.0,
            hovering: Vec::new(),
            dropping: Vec::new(),
            chip: None,
            modifiers: egui::Modifiers::NONE,
            fast_forward: 1,
            stepped: 0,
            stills,
        };
        // Let the fonts land before the first real frame.
        for _ in 0..3 {
            rec.harness.step();
        }
        rec
    }

    /// The app under the script.
    fn app(&mut self) -> &mut InterlaceApp {
        &mut self.harness.state_mut().app
    }

    /// Video time, in seconds.
    fn time(&self) -> f64 {
        self.frame as f64 / FPS as f64
    }

    // --- frames ---------------------------------------------------------------

    /// Step the app one frame, compose it onto the stage and write it.
    fn tick(&mut self) {
        let input = self.harness.input_mut();
        input.hovered_files = self
            .hovering
            .iter()
            .map(|p| egui::HoveredFile { path: Some(p.clone()), ..Default::default() })
            .collect();
        input.dropped_files = std::mem::take(&mut self.dropping)
            .into_iter()
            .map(|p| egui::DroppedFile { path: Some(p), ..Default::default() })
            .collect();
        input.modifiers = self.modifiers;
        self.harness.step();
        self.stepped += 1;
        if self.stepped % self.fast_forward != 0 {
            return;
        }

        // Without an encoder only stills are wanted; skip the per-frame render.
        if self.encoder.is_none() {
            self.frame += 1;
            return;
        }

        let app = self.render_app();
        let stage = self.render_stage();
        let frame = composite(stage, &app, 1.0 - self.card_alpha);
        if let Some((_, stdin)) = &mut self.encoder {
            stdin.write_all(frame.as_raw()).expect("ffmpeg stopped reading frames");
        }
        self.frame += 1;
    }

    /// Render `secs` of video.
    fn wait(&mut self, secs: f64) {
        for _ in 0..frames(secs) {
            self.tick();
        }
    }

    /// Keep rendering until `done` holds for the app (a probe or a run on a worker
    /// thread), sleeping a little per frame so the worker gets real time. Gives
    /// up after `timeout` seconds of wall time.
    fn wait_until(&mut self, timeout: f64, done: impl Fn(&InterlaceApp) -> bool) {
        let start = std::time::Instant::now();
        while !done(&self.harness.state().app) {
            assert!(start.elapsed().as_secs_f64() < timeout, "timed out waiting on the app");
            std::thread::sleep(std::time::Duration::from_millis(15));
            self.tick();
        }
    }

    /// The app frame as an image, with the recorder's cursor and click ripple.
    fn render_app(&mut self) -> image::RgbaImage {
        let mut output = self.harness.output().clone();
        let t = self.time();
        if let Some((at, pos)) = self.last_click {
            let k = ((t - at) / 0.45) as f32;
            if (0.0..1.0).contains(&k) {
                let ease = 1.0 - (1.0 - k).powi(3);
                let color = theme::ACCENT.gamma_multiply(0.8 * (1.0 - k));
                output.shapes.push(top(Shape::circle_stroke(pos, 6.0 + 18.0 * ease, Stroke::new(2.5, color))));
            }
        }
        if let Some(pos) = self.cursor {
            for shape in cursor_shapes(pos, self.pressed) {
                output.shapes.push(top(shape));
            }
        }
        self.app_renderer
            .borrow_mut()
            .render(&self.harness.ctx, &output)
            .expect("rendering the app frame")
    }

    // --- input ----------------------------------------------------------------

    /// Glide the cursor to `to` over a time that grows with the distance, with
    /// ease-in-out, as a hand moves a mouse.
    fn move_to(&mut self, to: Pos2) {
        let from = self.cursor.unwrap_or(pos2(WINDOW.x * 0.5, WINDOW.y + 40.0));
        let dist = from.distance(to);
        let secs = (0.25 + dist as f64 / 1400.0).min(0.9);
        self.glide(from, to, secs);
    }

    /// Move the cursor from `from` to `to` over `secs`, one pointer event a frame.
    fn glide(&mut self, from: Pos2, to: Pos2, secs: f64) {
        let n = frames(secs).max(1);
        for i in 1..=n {
            let p = from.lerp(to, ease(i as f32 / n as f32));
            self.pointer(p);
            self.tick();
        }
    }

    /// Put the cursor at `p` for the next frame.
    fn pointer(&mut self, p: Pos2) {
        self.cursor = Some(p);
        let inside = Rect::from_min_size(Pos2::ZERO, WINDOW).contains(p);
        let event = if inside { egui::Event::PointerMoved(p) } else { egui::Event::PointerGone };
        self.harness.input_mut().events.push(event);
    }

    /// Press or release the primary button where the cursor is.
    fn button(&mut self, pressed: bool) {
        let pos = self.cursor.expect("the cursor is on screen");
        self.pressed = pressed;
        self.harness.input_mut().events.push(egui::Event::PointerButton {
            pos,
            button: egui::PointerButton::Primary,
            pressed,
            modifiers: self.modifiers,
        });
        if pressed {
            self.last_click = Some((self.time(), pos));
        }
    }

    /// Move to `p` and click there, then let the result settle a moment.
    fn click(&mut self, p: Pos2) {
        self.move_to(p);
        self.wait(0.12);
        self.button(true);
        self.wait(0.08);
        self.button(false);
        self.wait(0.35);
    }

    /// Click with `modifiers` held (Ctrl- or Shift-click).
    fn click_with(&mut self, p: Pos2, modifiers: egui::Modifiers) {
        self.move_to(p);
        self.modifiers = modifiers;
        self.wait(0.15);
        self.button(true);
        self.wait(0.08);
        self.button(false);
        self.wait(0.1);
        self.modifiers = egui::Modifiers::NONE;
        self.wait(0.3);
    }

    /// Press at `from`, drag to `to` over `secs`, and release.
    fn drag(&mut self, from: Pos2, to: Pos2, secs: f64) {
        self.move_to(from);
        self.wait(0.15);
        self.button(true);
        self.wait(0.15);
        // A small first step so egui recognizes the drag before the long move.
        self.glide(from, from + vec2(0.0, 6.0), 0.1);
        self.glide(from + vec2(0.0, 6.0), to, secs);
        self.wait(0.25);
        self.button(false);
        self.wait(0.35);
    }

    /// Type `text` a character at a time.
    fn type_text(&mut self, text: &str) {
        for ch in text.chars() {
            self.harness.input_mut().events.push(egui::Event::Text(ch.to_string()));
            self.wait(0.055);
        }
    }

    /// Press and release `key` with the current modifiers.
    fn key(&mut self, key: egui::Key) {
        for pressed in [true, false] {
            self.harness.input_mut().events.push(egui::Event::Key {
                key,
                physical_key: None,
                pressed,
                repeat: false,
                modifiers: self.modifiers,
            });
            self.tick();
        }
    }

    /// Carry `files` in from off-window and hover them over `at`, as a drag
    /// from Explorer does: the drop overlay appears once they're over the window.
    fn hover_files(&mut self, files: &[PathBuf], at: Pos2) {
        let label = match files {
            [one] => one.file_name().unwrap().to_string_lossy().into_owned(),
            many => format!("{} files", many.len()),
        };
        self.chip = Some(label);
        let start = pos2(WINDOW.x + 60.0, at.y + 160.0);
        let n = frames(1.0);
        for i in 1..=n {
            let p = start.lerp(at, ease(i as f32 / n as f32));
            // An OS file drag sends no pointer events, only the hover.
            self.cursor = Some(p);
            self.harness.state_mut().chip = self.chip.clone().map(|l| (p, l));
            if p.x < WINDOW.x {
                self.hovering = files.to_vec();
            }
            self.tick();
        }
    }

    /// Release hovered files: they drop on the next frame.
    fn drop_files(&mut self) {
        self.dropping = std::mem::take(&mut self.hovering);
        self.chip = None;
        self.harness.state_mut().chip = None;
        if let Some(p) = self.cursor {
            self.last_click = Some((self.time(), p));
        }
        self.tick();
    }

    /// The center of the widget labelled `label`, in points. A leading icon
    /// glyph is ignored ("Remove" finds "🗑 Remove" but not "Remove input 0").
    fn find(&self, label: &str) -> Pos2 {
        let node = self
            .harness
            .query_all_by(|n| n.label().is_some_and(|l| l == label || l.ends_with(&format!(" {label}"))))
            .next()
            .unwrap_or_else(|| panic!("no widget labelled {label:?}"));
        (node.rect().center().to_vec2() / PPP).to_pos2()
    }

    /// Click the widget labelled `label`.
    fn click_label(&mut self, label: &str) {
        let p = self.find(label);
        self.click(p);
    }

    // --- story ----------------------------------------------------------------

    /// Show a caption under the app, crossfading from the previous one.
    fn caption(&mut self, tag: &str, title: &str, detail: &str) {
        self.old_caption = self.caption.take();
        self.caption = Some(Caption { tag: tag.into(), title: title.into(), detail: detail.into() });
        self.caption_since = self.time();
    }

    /// Show a full-screen card: fade it in over the app, or, when a card is
    /// already up, crossfade to this one's text without revealing the app.
    fn show_card(&mut self, card: Card) {
        self.old_card = self.card.replace(card);
        self.card_since = self.time();
        if self.old_card.is_none() {
            self.fade_card(true);
        }
    }

    /// Fade the card out, back to the app.
    fn hide_card(&mut self) {
        self.fade_card(false);
        self.card = None;
        self.old_card = None;
    }

    /// Fade the card's backdrop in or out over half a second.
    fn fade_card(&mut self, show: bool) {
        let n = frames(0.5);
        for i in 1..=n {
            let k = ease(i as f32 / n as f32);
            self.card_alpha = if show { k } else { 1.0 - k };
            self.tick();
        }
    }

    // --- stills ---------------------------------------------------------------

    /// Save the current composed frame as `name.png` (for checking the script).
    fn still(&mut self, name: &str) {
        let app = self.render_app();
        let stage = self.render_stage();
        let frame = composite(stage, &app, 1.0 - self.card_alpha);
        std::fs::create_dir_all(&self.stills).ok();
        frame.save(self.stills.join(format!("{name}.png"))).expect("saving a still");
    }

    /// Print every labelled widget with its rect (for writing the script).
    #[allow(dead_code)]
    fn dump(&self) {
        for node in self.harness.query_all_by(|_| true) {
            let label = node.accesskit_node().label().unwrap_or_default();
            if !label.is_empty() {
                println!("{:?} {label:?} {:?}", node.accesskit_node().role(), node.rect());
            }
        }
    }

    /// Finish the video.
    fn finish(mut self) {
        if let Some((mut child, stdin)) = self.encoder.take() {
            drop(stdin);
            assert!(child.wait().expect("waiting on ffmpeg").success(), "ffmpeg failed to encode");
        }
    }

    // --- stage ----------------------------------------------------------------

    /// The stage at this frame: backdrop, the app's shadow, caption and card.
    fn render_stage(&mut self) -> image::RgbaImage {
        let t = self.time();
        let size = vec2(VIDEO[0] as f32, VIDEO[1] as f32);
        let input = egui::RawInput {
            screen_rect: Some(Rect::from_min_size(Pos2::ZERO, size)),
            time: Some(t),
            ..Default::default()
        };
        let output = self.stage.run_ui(input, |ui| {
            let painter = ui.painter();
            backdrop(painter, size, t);
            let app_rect = Rect::from_min_size(
                pos2(APP_ORIGIN[0] as f32, APP_ORIGIN[1] as f32),
                vec2(WINDOW.x * PPP, WINDOW.y * PPP),
            );
            let app_alpha = 1.0 - self.card_alpha;
            if app_alpha > 0.0 {
                let shadow = egui::Shadow { offset: [0, 18], blur: 48, spread: 2, color: Color32::from_black_alpha(150) };
                painter.add(Shape::from(shadow.as_shape(app_rect, APP_RADIUS)));
                painter.rect_stroke(
                    app_rect.expand(1.0),
                    APP_RADIUS + 1.0,
                    Stroke::new(1.0, theme::BUTTON_STROKE.gamma_multiply(app_alpha)),
                    egui::StrokeKind::Outside,
                );
            }
            let caption_top = app_rect.bottom() + 22.0;
            let fade = ((t - self.caption_since) / 0.35).clamp(0.0, 1.0) as f32;
            if let Some(old) = &self.old_caption {
                draw_caption(painter, old, caption_top, (1.0 - fade) * app_alpha, -8.0 * fade);
            }
            if let Some(cap) = &self.caption {
                draw_caption(painter, cap, caption_top, fade * app_alpha, 8.0 * (1.0 - fade));
            }
            if self.card_alpha > 0.0 {
                let screen = Rect::from_min_size(Pos2::ZERO, size);
                painter.rect_filled(screen, 0.0, theme::BG.gamma_multiply(self.card_alpha));
                radial_glow(painter, pos2(size.x * 0.5, size.y * 0.45), 760.0, theme::ACCENT.gamma_multiply(0.14 * self.card_alpha));
                let since = (t - self.card_since) as f32;
                let k = ease((since / 0.5).clamp(0.0, 1.0));
                if let Some(old) = &self.old_card {
                    draw_card(painter, old, size, self.card_alpha * (1.0 - k), -10.0 * k, f32::MAX, &self.logo);
                }
                if let Some(card) = &self.card {
                    draw_card(painter, card, size, self.card_alpha * k, 14.0 * (1.0 - k), since, &self.logo);
                }
            }
        });
        self.stage_renderer.handle_delta(&output.textures_delta);
        self.stage_renderer.render(&self.stage, &output).expect("rendering the stage")
    }
}

/// The chip a dragged file shows by the cursor: a file icon and its name.
fn file_chip(ctx: &egui::Context, pos: Pos2, label: &str) {
    let painter = ctx.layer_painter(egui::LayerId::new(egui::Order::Tooltip, egui::Id::new("demo_chip")));
    let text = format!("{}  {label}", egui_phosphor::regular::FILE);
    let galley = painter.layout_no_wrap(text, egui::FontId::proportional(13.0), theme::TEXT);
    let rect = Rect::from_min_size(pos + vec2(18.0, 18.0), galley.size() + vec2(20.0, 12.0));
    let shadow = egui::Shadow { offset: [0, 4], blur: 14, spread: 0, color: Color32::from_black_alpha(120) };
    painter.add(Shape::from(shadow.as_shape(rect, 6.0)));
    painter.rect(rect, 6.0, theme::CARD, Stroke::new(1.0, theme::ACCENT), egui::StrokeKind::Inside);
    painter.galley(rect.min + vec2(10.0, 6.0), galley, theme::TEXT);
}

/// Smoothstep: eases a 0..1 fade in and out.
fn ease(k: f32) -> f32 {
    k * k * (3.0 - 2.0 * k)
}

/// A point in the app given in video pixels, as read off a still: the app's
/// origin is subtracted and the window scale undone.
fn px(x: f32, y: f32) -> Pos2 {
    pos2((x - APP_ORIGIN[0] as f32) / PPP, (y - APP_ORIGIN[1] as f32) / PPP)
}

/// A wgpu setup on the real GPU. kittest's default prefers a software
/// rasterizer, which keeps snapshot tests identical across machines but takes
/// most of a second per 1080p frame; a video only needs to look right.
fn gpu_setup() -> egui_wgpu::WgpuSetup {
    let mut setup = egui_wgpu::WgpuSetupCreateNew::without_display_handle();
    setup.native_adapter_selector = Some(std::sync::Arc::new(|adapters, _surface| {
        let rank = |a: &&egui_wgpu::wgpu::Adapter| match a.get_info().device_type {
            egui_wgpu::wgpu::DeviceType::DiscreteGpu => 0,
            egui_wgpu::wgpu::DeviceType::IntegratedGpu => 1,
            egui_wgpu::wgpu::DeviceType::Cpu => 3,
            _ => 2,
        };
        adapters.iter().min_by_key(rank).cloned().ok_or_else(|| "No adapter found".to_owned())
    }));
    egui_wgpu::WgpuSetup::CreateNew(setup)
}

/// The number of frames in `secs` of video.
fn frames(secs: f64) -> u64 {
    (secs * FPS as f64).round() as u64
}

/// A shape on top of everything else in the app frame.
fn top(shape: Shape) -> egui::epaint::ClippedShape {
    egui::epaint::ClippedShape { clip_rect: Rect::EVERYTHING, shape }
}

/// A desktop arrow cursor with its tip at `tip`, a little smaller while pressed.
fn cursor_shapes(tip: Pos2, pressed: bool) -> Vec<Shape> {
    let s = if pressed { 0.9 } else { 1.0 };
    let p = |x: f32, y: f32| tip + vec2(x, y) * s;
    let outline = vec![p(0.0, 0.0), p(0.0, 17.0), p(4.2, 13.2), p(7.0, 19.4), p(9.8, 18.2), p(7.1, 12.2), p(12.6, 12.2)];
    let dark = Color32::from_rgb(0x06, 0x08, 0x0C);
    vec![
        Shape::convex_polygon(vec![p(0.5, 3.0), p(0.5, 19.0), p(14.0, 13.5)], Color32::from_black_alpha(60), Stroke::NONE),
        Shape::closed_line(outline, Stroke::new(2.4, dark)),
        Shape::convex_polygon(vec![p(0.0, 0.0), p(0.0, 17.0), p(4.2, 13.2), p(12.6, 12.2)], Color32::WHITE, Stroke::NONE),
        Shape::convex_polygon(vec![p(4.2, 13.2), p(7.1, 12.2), p(9.8, 18.2), p(7.0, 19.4)], Color32::WHITE, Stroke::NONE),
    ]
}

/// The stage backdrop: the app's background color, lit by two slow, soft glows
/// in the accent and subtitle hues.
fn backdrop(painter: &egui::Painter, size: Vec2, t: f64) {
    painter.rect_filled(Rect::from_min_size(Pos2::ZERO, size), 0.0, theme::BG);
    let t = t as f32;
    let glows = [
        (pos2(size.x * (0.22 + 0.04 * (t * 0.11).sin()), size.y * 0.18), theme::ACCENT, 900.0),
        (pos2(size.x * (0.82 + 0.03 * (t * 0.07).cos()), size.y * 0.92), theme::KIND_AUDIO, 800.0),
    ];
    for (center, color, radius) in glows {
        radial_glow(painter, center, radius, color.gamma_multiply(0.16));
    }
}

/// A radial gradient from `color` at `center` to transparent at `radius`.
fn radial_glow(painter: &egui::Painter, center: Pos2, radius: f32, color: Color32) {
    let mut mesh = egui::Mesh::default();
    // Many thin rings, or the 8-bit video shows each one as a band.
    let rings = 96;
    let segments = 96;
    for r in 0..=rings {
        let k = r as f32 / rings as f32;
        // Smooth falloff: bright core, long soft tail.
        let a = (1.0 - k).powf(2.2);
        for s in 0..segments {
            let angle = s as f32 / segments as f32 * std::f32::consts::TAU;
            mesh.colored_vertex(center + radius * k * vec2(angle.cos(), angle.sin()), color.gamma_multiply(a));
        }
    }
    for r in 0..rings {
        for s in 0..segments {
            let a = r * segments + s;
            let b = r * segments + (s + 1) % segments;
            let (c, d) = (a + segments, b + segments);
            mesh.add_triangle(a, b, c);
            mesh.add_triangle(b, d, c);
        }
    }
    painter.add(Shape::mesh(mesh));
}

/// A caption under the app window, `alpha` opaque, nudged down by `dy`.
fn draw_caption(painter: &egui::Painter, cap: &Caption, top: f32, alpha: f32, dy: f32) {
    if alpha <= 0.0 {
        return;
    }
    let x = APP_ORIGIN[0] as f32 + 4.0;
    let y = top + dy;
    let tag = painter.layout_no_wrap(cap.tag.clone(), theme::medium_font(15.0), theme::ACCENT.gamma_multiply(alpha));
    painter.galley(pos2(x, y + 9.0), tag.clone(), Color32::WHITE);
    let tx = x + tag.size().x + 18.0;
    painter.line_segment(
        [pos2(tx - 9.0, y + 6.0), pos2(tx - 9.0, y + 64.0)],
        Stroke::new(1.0, theme::STROKE.gamma_multiply(alpha)),
    );
    painter.text(pos2(tx, y), egui::Align2::LEFT_TOP, &cap.title, theme::medium_font(30.0), theme::TEXT.gamma_multiply(alpha));
    painter.text(
        pos2(tx, y + 42.0),
        egui::Align2::LEFT_TOP,
        &cap.detail,
        egui::FontId::proportional(19.0),
        theme::WEAK.gamma_multiply(alpha),
    );
}

/// A card's content (the backdrop is drawn once, under it): `alpha` opaque,
/// nudged down by `dy`, `since` seconds into its art's animation.
fn draw_card(painter: &egui::Painter, card: &Card, size: Vec2, alpha: f32, dy: f32, since: f32, logo: &egui::TextureHandle) {
    if alpha <= 0.0 {
        return;
    }
    let mut y = size.y * 0.5 - 40.0 - 22.0 * card.lines.len() as f32 + dy;
    if card.art {
        y -= 150.0;
    }
    if card.logo {
        y -= 70.0;
        let r = Rect::from_center_size(pos2(size.x * 0.5, y - 40.0), vec2(120.0, 120.0));
        painter.image(logo.id(), r, Rect::from_min_max(Pos2::ZERO, pos2(1.0, 1.0)), Color32::WHITE.gamma_multiply(alpha));
        y += 60.0;
    }
    let center = |y: f32| pos2(size.x * 0.5, y);
    if !card.tag.is_empty() {
        painter.text(center(y), egui::Align2::CENTER_TOP, &card.tag, theme::medium_font(18.0), theme::ACCENT.gamma_multiply(alpha));
        y += 36.0;
    }
    let title_size = if card.logo { 84.0 } else { 56.0 };
    painter.text(center(y), egui::Align2::CENTER_TOP, &card.title, theme::medium_font(title_size), theme::TEXT.gamma_multiply(alpha));
    y += title_size * 1.25 + 14.0;
    for line in &card.lines {
        painter.text(center(y), egui::Align2::CENTER_TOP, line, egui::FontId::proportional(25.0), theme::WEAK.gamma_multiply(alpha));
        y += 38.0;
    }
    if card.art {
        stream_art(painter, size.x * 0.5, y + 70.0, since, alpha);
    }
}

/// One stream in the idea card's animation.
struct ArtStream {
    /// Kind label and color, as the table's badge shows them.
    kind: &'static str,
    color: Color32,
    /// What the stream is.
    text: &'static str,
}

/// The idea card's animation: a file's streams as a row of chips that get
/// reordered, one removed and one inserted, with the `-map` list under them
/// rewritten at each step. `t` is seconds since the card appeared.
fn stream_art(painter: &egui::Painter, cx: f32, top: f32, t: f32, alpha: f32) {
    let streams = [
        ArtStream { kind: "video", color: theme::KIND_VIDEO, text: "h264" },
        ArtStream { kind: "audio", color: theme::KIND_AUDIO, text: "flac · jpn" },
        ArtStream { kind: "audio", color: theme::KIND_AUDIO, text: "ac3 · eng" },
        ArtStream { kind: "audio", color: theme::KIND_AUDIO, text: "commentary" },
        ArtStream { kind: "subtitle", color: theme::KIND_SUBTITLE, text: "srt · por" },
    ];
    let phase = |a: f32, b: f32| ease(((t - a) / (b - a)).clamp(0.0, 1.0));
    let swap = phase(1.3, 2.0); // flac and ac3 trade places
    let remove = phase(2.5, 3.0); // commentary is struck out
    let insert = phase(3.4, 4.1); // the subtitle slides in

    let (w, h, gap) = (210.0, 48.0, 16.0);
    let count = 4.0 + insert;
    let left = cx - (count * w + (count - 1.0) * gap) / 2.0;
    let slot_x = |slot: f32| left + slot * (w + gap);
    // Slot (possibly between two, mid-swap) and vertical lift per stream.
    let place = [
        (0.0, 0.0),
        (1.0 + swap, 26.0 * (swap * std::f32::consts::PI).sin()),
        (2.0 - swap, -26.0 * (swap * std::f32::consts::PI).sin()),
        (3.0, 0.0),
        (4.0, 40.0 * (1.0 - insert)),
    ];
    for (i, (s, (slot, lift))) in streams.iter().zip(place).enumerate() {
        let appear = if i == 4 { insert } else { phase(0.1 * i as f32, 0.1 * i as f32 + 0.5) };
        let a = alpha * appear;
        if a <= 0.0 {
            continue;
        }
        let rect = Rect::from_min_size(pos2(slot_x(slot), top + lift), vec2(w, h));
        let removed = i == 3 && remove > 0.0;
        let fill = if removed { lerp_color(theme::CARD, theme::REMOVED, remove) } else { theme::CARD };
        let stroke = if i == 4 || (i == 1 || i == 2) && swap > 0.0 && swap < 1.0 { theme::ACCENT } else { theme::STROKE };
        painter.rect(rect, 10.0, fill.gamma_multiply(a), Stroke::new(1.0, stroke.gamma_multiply(a)), egui::StrokeKind::Inside);
        let badge = painter.layout_no_wrap(s.kind.into(), theme::medium_font(14.0), theme::TEXT.gamma_multiply(a));
        let badge_rect = Rect::from_min_size(rect.left_center() + vec2(12.0, -11.0), vec2(badge.size().x + 14.0, 22.0));
        painter.rect_filled(badge_rect, 5.0, s.color.gamma_multiply(a * if removed { 1.0 - 0.6 * remove } else { 1.0 }));
        painter.galley(badge_rect.center() - badge.size() / 2.0, badge, theme::TEXT);
        let text_color = if removed { lerp_color(theme::TEXT, theme::DIM, remove) } else { theme::TEXT };
        let galley = painter.layout_no_wrap(s.text.into(), egui::FontId::proportional(18.0), text_color.gamma_multiply(a));
        let text_pos = pos2(badge_rect.right() + 12.0, rect.center().y - galley.size().y / 2.0);
        let text_w = galley.size().x;
        painter.galley(text_pos, galley, theme::TEXT);
        if removed {
            let y = rect.center().y;
            let x0 = badge_rect.left();
            let x1 = x0 + (text_pos.x + text_w - x0) * remove;
            painter.line_segment([pos2(x0, y), pos2(x1, y)], Stroke::new(2.0, theme::ERROR.gamma_multiply(a)));
        }
    }

    // The command the list becomes, rewritten at each step.
    let commands = [
        "ffmpeg -i movie.mkv -map 0:0 -map 0:1 -map 0:2 -map 0:3 -c copy out.mkv",
        "ffmpeg -i movie.mkv -map 0:0 -map 0:2 -map 0:1 -map 0:3 -c copy out.mkv",
        "ffmpeg -i movie.mkv -map 0:0 -map 0:2 -map 0:1 -c copy out.mkv",
        "ffmpeg -i movie.mkv -i subs.pt-BR.srt -map 0:0 -map 0:2 -map 0:1 -map 1:0 -c copy out.mkv",
    ];
    let steps = [(0.0, 0.6), (1.8, 2.2), (2.8, 3.2), (3.9, 4.3)];
    let y = top + h + 52.0;
    for (i, (cmd, (a, b))) in commands.iter().zip(steps).enumerate() {
        // The old line is gone before the new one comes in: two monospace
        // lines crossfading on the same spot read as noise.
        let mid = (a + b) / 2.0;
        let fade_in = if i == 0 { phase(a, b) } else { phase(mid, b) };
        let fade_out = steps.get(i + 1).map_or(0.0, |&(a, b)| phase(a, (a + b) / 2.0));
        let shown = fade_in * (1.0 - fade_out);
        if shown > 0.0 {
            painter.text(
                pos2(cx, y + 6.0 * (1.0 - shown)),
                egui::Align2::CENTER_TOP,
                *cmd,
                egui::FontId::monospace(20.0),
                theme::CODE.gamma_multiply(alpha * shown),
            );
        }
    }
}

/// `a` blended toward `b` by `k` (0..1).
fn lerp_color(a: Color32, b: Color32, k: f32) -> Color32 {
    let mix = |x: u8, y: u8| (x as f32 + (y as f32 - x as f32) * k).round() as u8;
    Color32::from_rgb(mix(a.r(), b.r()), mix(a.g(), b.g()), mix(a.b(), b.b()))
}

/// Paste `app` onto `stage` at `APP_ORIGIN` with rounded corners, `alpha` opaque.
fn composite(mut stage: image::RgbaImage, app: &image::RgbaImage, alpha: f32) -> image::RgbaImage {
    if alpha <= 0.0 {
        return stage;
    }
    let (w, h) = app.dimensions();
    let [ox, oy] = APP_ORIGIN;
    for y in 0..h {
        for x in 0..w {
            let cover = corner_coverage(x as f32 + 0.5, y as f32 + 0.5, w as f32, h as f32) * alpha;
            if cover <= 0.0 {
                continue;
            }
            // The app image is premultiplied; where egui painted nothing (the
            // root area around the panels) it's transparent, and the window
            // background shows instead.
            let src = app.get_pixel(x, y).0;
            let a = src[3] as f32 / 255.0;
            let bg = theme::BG.to_array();
            let dst = stage.get_pixel_mut(x + ox, y + oy);
            for c in 0..3 {
                let px = src[c] as f32 + bg[c] as f32 * (1.0 - a);
                dst.0[c] = (px * cover + dst.0[c] as f32 * (1.0 - cover)).round() as u8;
            }
            dst.0[3] = 255;
        }
    }
    stage
}

/// How much of pixel (`x`, `y`) lies inside a `w`×`h` rect with `APP_RADIUS`
/// corners: 1 inside, 0 outside, antialiased along the curve.
fn corner_coverage(x: f32, y: f32, w: f32, h: f32) -> f32 {
    let r = APP_RADIUS;
    let cx = if x < r { r } else if x > w - r { w - r } else { return 1.0 };
    let cy = if y < r { r } else if y > h - r { h - r } else { return 1.0 };
    let d = ((x - cx).powi(2) + (y - cy).powi(2)).sqrt();
    (r - d + 0.5).clamp(0.0, 1.0)
}

